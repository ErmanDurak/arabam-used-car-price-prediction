import streamlit as st
import pandas as pd
import joblib
import os

st.set_page_config(
    page_title="Used Car Price Predictor",
    page_icon="🚗",
    layout="wide"
)

MODEL_PATH = "models/best_car_price_model.joblib"
DATA_PATH = "data/processed/cleaned_arabam.csv"

@st.cache_resource
def load_model():
    if not os.path.exists(MODEL_PATH):
        st.error(f"Model file not found at {MODEL_PATH}. Please run `python src/train.py` first.")
        return None
    return joblib.load(MODEL_PATH)

@st.cache_data
def load_reference_data():
    if not os.path.exists(DATA_PATH):
        st.error(f"Data file not found at {DATA_PATH}.")
        return None
    return pd.read_csv(DATA_PATH)

def clean_unique_list(series):
    return sorted([str(x) for x in series.dropna().unique()])

model_pipeline = load_model()
ref_df = load_reference_data()

st.title("🚗 Used Car Valuation & Price Prediction System")
st.markdown("Estimate market value in real-time powered by an optimized **LightGBM Machine Learning Pipeline**.")
st.divider()

if model_pipeline is not None and ref_df is not None:
    col1, col2 = st.columns(2)
    
    with col1:
        st.subheader("📋 General Vehicle Specifications")
        
        brands = clean_unique_list(ref_df["brand"])
        selected_brand = st.selectbox("Brand / Make", options=brands)
        
        brand_series = ref_df[ref_df["brand"] == selected_brand]["series"]
        available_series = clean_unique_list(brand_series)
        selected_series = st.selectbox("Series / Family", options=available_series)
        
        transmissions = clean_unique_list(ref_df["transmission"])
        selected_transmission = st.selectbox("Transmission Type", options=transmissions)
        
        fuel_types = clean_unique_list(ref_df["fuel_type"])
        selected_fuel = st.selectbox("Fuel Type", options=fuel_types)
        
        body_types = clean_unique_list(ref_df["body_type"])
        selected_body = st.selectbox("Body Type", options=body_types)

    with col2:
        st.subheader("⚙️ Technical Features & Condition")
        
        selected_year = st.number_input("Model Year", min_value=1990, max_value=2026, value=2017, step=1)
        selected_km = st.number_input("Mileage (KM)", min_value=0, max_value=1000000, value=120000, step=5000)
        
        engine_cc = st.number_input("Engine Displacement (cc)", min_value=500, max_value=6000, value=1598, step=100)
        engine_hp = st.number_input("Engine Power (hp)", min_value=40, max_value=1000, value=110, step=5)
        fuel_cons = st.number_input("Avg. Fuel Consumption (l/100km)", min_value=2.0, max_value=20.0, value=4.8, step=0.1)
        
        st.markdown("**Vehicle Inspection & Damage History**")
        c1, c2, c3 = st.columns(3)
        with c1:
            painted_cnt = st.number_input("Repainted Parts", min_value=0, max_value=15, value=0, step=1)
        with c2:
            local_painted_cnt = st.number_input("Locally Painted", min_value=0, max_value=15, value=0, step=1)
        with c3:
            changed_cnt = st.number_input("Replaced Parts", min_value=0, max_value=15, value=0, step=1)
            
        color_options = clean_unique_list(ref_df["color"])
        selected_color = st.selectbox("Exterior Color", options=color_options)
        
        drivetrain_options = clean_unique_list(ref_df["drivetrain"])
        selected_drivetrain = st.selectbox("Drivetrain", options=drivetrain_options)

    st.divider()
    
    if st.button("💰 Predict Estimated Price", type="primary", use_container_width=True):
        input_data = pd.DataFrame([{
            "brand": selected_brand,
            "series": selected_series,
            "year": selected_year,
            "kilometer": selected_km,
            "engine_displacement_cc": engine_cc,
            "engine_power_hp": engine_hp,
            "avg_fuel_consumption": fuel_cons,
            "painted_count": painted_cnt,
            "local_painted_count": local_painted_cnt,
            "changed_count": changed_cnt,
            "is_original": 1 if (painted_cnt == 0 and local_painted_cnt == 0 and changed_cnt == 0) else 0,
            "transmission": selected_transmission,
            "fuel_type": selected_fuel,
            "body_type": selected_body,
            "color": selected_color,
            "drivetrain": selected_drivetrain
        }])
        
        predicted_price = model_pipeline.predict(input_data)[0]
        
        st.balloons()
        st.success(f"### Estimated Market Value: **{predicted_price:,.0f} TRY**")
        st.info("💡 *This valuation is generated by analyzing your selected vehicle parameters using our trained LightGBM model pipeline.*")